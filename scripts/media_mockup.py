"""Visual agent: composite app screenshots into promo images.

Deterministic compositor (Pillow): gradient or AI backdrop + rounded screenshot
+ shadow + caption. With --comfy, the backdrop is generated by the local
ComfyUI server (127.0.0.1:8188) instead of a gradient — the script degrades
gracefully when the server is off.

    python scripts/media_mockup.py shot.png --tag v1.3.4
    python scripts/media_mockup.py --capture --tag v1.3.4 --comfy "dark purple nebula, soft bokeh"
"""
import argparse
import io
import json
import math
import random
import time
import urllib.request
import urllib.parse
from pathlib import Path

from PIL import Image, ImageDraw, ImageFilter, ImageFont

ROOT = Path(__file__).resolve().parents[1]
COMFY = "http://127.0.0.1:8188"
CKPT = "v1-5-pruned-emaonly-fp16.safetensors"
CANVAS = (1600, 900)


def rounded(img, radius):
    mask = Image.new("L", img.size, 0)
    ImageDraw.Draw(mask).rounded_rectangle([0, 0, *img.size], radius, fill=255)
    out = img.convert("RGBA")
    out.putalpha(mask)
    return out


def drop_shadow(size, radius, blur, alpha=140):
    layer = Image.new("RGBA", size, (0, 0, 0, 0))
    d = ImageDraw.Draw(layer)
    pad = blur * 2
    d.rounded_rectangle([pad, pad, size[0] - pad, size[1] - pad], radius, fill=(0, 0, 0, alpha))
    return layer.filter(ImageFilter.GaussianBlur(blur))


def gradient(size, c1=(16, 18, 38), c2=(60, 26, 90)):
    base = Image.new("RGB", size, c1)
    top = Image.new("RGB", size, c2)
    mask = Image.linear_gradient("L").resize(size).rotate(35, expand=False)
    return Image.composite(top, base, mask)


def comfy_up():
    try:
        urllib.request.urlopen(f"{COMFY}/system_stats", timeout=3)
        return True
    except Exception:
        return False


def comfy_image(prompt, w=CANVAS[0], h=CANVAS[1], seed=None):
    seed = seed if seed is not None else random.randint(1, 2**40)
    workflow = {
        "1": {"class_type": "CheckpointLoaderSimple", "inputs": {"ckpt_name": CKPT}},
        "2": {"class_type": "CLIPTextEncode", "inputs": {"text": prompt, "clip": ["1", 1]}},
        "3": {"class_type": "CLIPTextEncode", "inputs": {"text": "text, watermark, ui, blurry, lowres", "clip": ["1", 1]}},
        "4": {"class_type": "EmptyLatentImage", "inputs": {"width": w, "height": h, "batch_size": 1}},
        "5": {"class_type": "KSampler", "inputs": {"seed": seed, "steps": 20, "cfg": 7.0,
              "sampler_name": "euler", "scheduler": "normal", "denoise": 1.0,
              "model": ["1", 0], "positive": ["2", 0], "negative": ["3", 0], "latent_image": ["4", 0]}},
        "6": {"class_type": "VAEDecode", "inputs": {"samples": ["5", 0], "vae": ["1", 2]}},
        "7": {"class_type": "SaveImage", "inputs": {"filename_prefix": "coredesk_backdrop", "images": ["6", 0]}},
    }
    req = urllib.request.Request(f"{COMFY}/prompt", json.dumps({"prompt": workflow}).encode(),
                                 {"Content-Type": "application/json"})
    pid = json.loads(urllib.request.urlopen(req, timeout=30).read())["prompt_id"]
    for _ in range(180):
        time.sleep(2)
        hist = json.loads(urllib.request.urlopen(f"{COMFY}/history/{pid}", timeout=10).read())
        if pid in hist:
            imgs = hist[pid]["outputs"]["7"]["images"]
            q = urllib.parse.urlencode(imgs[0])
            return Image.open(io.BytesIO(urllib.request.urlopen(f"{COMFY}/view?{q}", timeout=30).read()))
    raise TimeoutError("ComfyUI job did not finish in 6 minutes")


def pexels_key():
    p = ROOT / "secrets" / "pexels.json"
    if p.exists():
        try:
            return json.loads(p.read_text(encoding="utf-8")).get("api_key")
        except (OSError, json.JSONDecodeError):
            return None
    return None


def pexels_image(query):
    key = pexels_key()
    if not key:
        return None
    url = "https://api.pexels.com/v1/search?" + urllib.parse.urlencode(
        {"query": query, "orientation": "landscape", "per_page": 15})
    req = urllib.request.Request(url, headers={"Authorization": key})
    photos = json.loads(urllib.request.urlopen(req, timeout=20).read()).get("photos", [])
    if not photos:
        return None
    src = random.choice(photos)["src"]["large2x"]
    return Image.open(io.BytesIO(urllib.request.urlopen(src, timeout=60).read()))


def font(size):
    for name in ("segoeui.ttf", "arial.ttf", "DejaVuSans.ttf"):
        try:
            return ImageFont.truetype(name, size)
        except OSError:
            pass
    return ImageFont.load_default()


def compose(shot, backdrop, tag, out_path):
    canvas = backdrop.resize(CANVAS).filter(ImageFilter.GaussianBlur(4)).convert("RGBA")
    dim = Image.new("RGBA", CANVAS, (8, 8, 20, 110))
    canvas = Image.alpha_composite(canvas, dim)

    sw = int(CANVAS[0] * 0.78)
    sh = int(shot.height * sw / shot.width)
    shot = rounded(shot.resize((sw, sh), Image.LANCZOS), 14)

    pad = 60
    shadow = drop_shadow((sw + pad * 2, sh + pad * 2), 14, 28)
    x, y = (CANVAS[0] - sw) // 2, (CANVAS[1] - sh) // 2 + 16
    canvas.alpha_composite(shadow, (x - pad, y - pad + 14))
    canvas.alpha_composite(shot, (x, y))

    d = ImageDraw.Draw(canvas)
    d.text((56, CANVAS[1] - 74), f"CoreDesk Engine  •  {tag}  •  ko-fi.com/fox881",
           font=font(30), fill=(235, 235, 245, 255))
    out_path.parent.mkdir(parents=True, exist_ok=True)
    canvas.convert("RGB").save(out_path, quality=92)
    return out_path


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("shot", nargs="?", help="screenshot path (or --capture for fullscreen)")
    ap.add_argument("--capture", action="store_true", help="grab the primary screen via PIL")
    ap.add_argument("--tag", default="", help="release tag printed on the promo")
    ap.add_argument("--comfy", default="", help="prompt for an AI backdrop via local ComfyUI")
    ap.add_argument("--pexels", default="", help="query for a Pexels stock backdrop (needs secrets/pexels.json)")
    ap.add_argument("--out", default="out/media")
    args = ap.parse_args()

    if args.capture:
        from PIL import ImageGrab
        shot = ImageGrab.grab()
    elif args.shot:
        shot = Image.open(args.shot)
    else:
        ap.error("give a screenshot path or --capture")

    backdrop = None
    if args.comfy and comfy_up():
        print("ComfyUI is up — generating backdrop…")
        backdrop = comfy_image(args.comfy)
    elif args.comfy:
        print("ComfyUI offline — trying Pexels / gradient")
    if backdrop is None and args.pexels:
        backdrop = pexels_image(args.pexels)
        print("pexels backdrop" if backdrop else "pexels unavailable — gradient")
    if backdrop is None:
        backdrop = gradient(CANVAS)

    name = f"promo_{args.tag or 'shot'}.png"
    print("saved:", compose(shot, backdrop, args.tag, ROOT / args.out / name))


if __name__ == "__main__":
    main()
